// Generates the example index and the slug -> examples map.
// Run: node scripts/gen-examples.mjs   (also runs before dev/build)
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const dir = path.join(root, "components/examples")
const registry = fs.readFileSync(path.join(root, "lib/registry.ts"), "utf8")

const names = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".tsx") && f !== "client.tsx")
  .map((f) => f.slice(0, -4))
  .sort()

// Component slugs, and the file prefix each one uses.
const slugs = [...registry.matchAll(/^\s*c\("([a-z-]+)"/gm)].map((m) => m[1])
const prefixOf = (slug) => (slug === "toast" ? "sonner" : slug)

// Examples pinned right after the hero, in this order.
const pinned = ["button-callout", "tabs-segmented"]

const bySlug = {}
for (const name of names) {
  let best = null
  for (const slug of slugs) {
    const p = prefixOf(slug)
    if ((name === p || name.startsWith(p + "-")) && (!best || p.length > prefixOf(best).length)) best = slug
  }
  if (best) (bySlug[best] ??= []).push(name)
}

for (const slug of Object.keys(bySlug)) {
  const hero = `${prefixOf(slug)}-demo`
  bySlug[slug].sort((a, b) => {
    const rank = (n) => (n === hero ? -2 : pinned.includes(n) ? -1 : 0)
    return rank(a) - rank(b) || a.localeCompare(b)
  })
}

// Async examples must stay Server Components; the rest load lazily on the client.
const isServer = (n) => {
  const src = fs.readFileSync(path.join(dir, `${n}.tsx`), "utf8")
  return !/^\s*["']use client["']/.test(src) && /^(export (default )?)?async function/m.test(src)
}
const serverNames = names.filter(isServer)
const clientNames = names.filter((n) => !isServer(n))

const pick = [
  "type Mod = Record<string, unknown>",
  "const pick = (m: Mod) =>",
  '  (m.default ?? Object.values(m).find((v) => typeof v === "function")) as React.ComponentType',
]

// One chunk per example, so a page only downloads the demos it shows.
const client = [
  '"use client"',
  "// Generated by scripts/gen-examples.mjs. Do not edit.",
  'import type * as React from "react"',
  'import dynamic from "next/dynamic"',
  "",
  ...pick,
  "",
  "const lazy: Record<string, React.ComponentType> = {",
  ...clientNames.map((n) => `  "${n}": dynamic(() => import("./${n}").then((m) => pick(m as Mod))),`),
  "}",
  "",
  "export function ClientExample({ name }: { name: string }) {",
  "  const Example = lazy[name]",
  "  return Example ? <Example /> : null",
  "}",
  "",
].join("\n")

const index = [
  "// Generated by scripts/gen-examples.mjs. Do not edit.",
  'import * as React from "react"',
  "",
  'import { ClientExample } from "./client"',
  ...serverNames.map((n, i) => `import * as s${i} from "./${n}"`),
  "",
  ...pick,
  "const client = (name: string) => () => React.createElement(ClientExample, { name })",
  "",
  "export const examples: Record<string, React.ComponentType> = {",
  ...clientNames.map((n) => `  "${n}": client("${n}"),`),
  ...serverNames.map((n, i) => `  "${n}": pick(s${i} as Mod),`),
  "}",
  "",
].join("\n")

fs.writeFileSync(path.join(dir, "client.tsx"), client)

fs.writeFileSync(path.join(dir, "index.ts"), index)
fs.writeFileSync(
  path.join(root, "lib/examples.generated.ts"),
  "// Generated by scripts/gen-examples.mjs. Do not edit.\nexport const examplesBySlug: Record<string, string[]> = " +
    JSON.stringify(bySlug, null, 2) +
    "\n"
)
console.log(`${names.length} examples, ${Object.keys(bySlug).length} components`)
